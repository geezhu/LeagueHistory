param(
    [string]$UpstreamRef = '',
    [switch]$Check
)

$ErrorActionPreference = 'Stop'
$repository = Split-Path $PSScriptRoot -Parent
$configurationPath = Join-Path $repository 'config/code-quality.json'
$configuration = Get-Content -LiteralPath $configurationPath -Raw | ConvertFrom-Json

if ($UpstreamRef) {
    if ($Check) { throw '-Check cannot update the upstream baseline.' }
    $commit = & git -C $repository rev-parse --verify "$UpstreamRef^{commit}"
    if ($LASTEXITCODE -ne 0) { throw 'The upstream reference does not resolve to a commit.' }
    $upstreamPaths = @(& git -C $repository ls-tree -r --name-only $commit)
    if ($LASTEXITCODE -ne 0) { throw 'Unable to read the upstream tree.' }
    $configuration.upstreamCommit = $commit.Trim()
    # Once upstream-owned, always excluded: deleting a file upstream does not transfer ownership.
    $configuration.upstreamFiles = @(
        @($configuration.upstreamFiles) + @($upstreamPaths | Where-Object { $_ -match '\.(cs|cpp|h|hpp|inl)$' }) |
            Sort-Object -Unique
    )
    $configuration | ConvertTo-Json -Depth 5 | Set-Content -LiteralPath $configurationPath -Encoding UTF8
}

$style = [ordered]@{
    charset = 'utf-8'
    indent_style = 'space'
    indent_size = '4'
    end_of_line = 'crlf'
    insert_final_newline = 'true'
    trim_trailing_whitespace = 'true'
    max_line_length = '120'
    csharp_new_line_before_open_brace = 'all'
    csharp_new_line_before_else = 'true'
    csharp_new_line_before_catch = 'true'
    csharp_new_line_before_finally = 'true'
    csharp_new_line_before_members_in_object_initializers = 'true'
    csharp_preserve_single_line_statements = 'false'
    csharp_preserve_single_line_blocks = 'false'
    csharp_prefer_braces = 'true:warning'
    'dotnet_diagnostic.IDE0011.severity' = 'warning'
    'dotnet_diagnostic.MA0040.severity' = 'warning'
    'dotnet_diagnostic.MA0042.severity' = 'warning'
    'dotnet_diagnostic.MA0051.severity' = 'warning'
    'dotnet_diagnostic.MA0054.severity' = 'warning'
    'MA0051.maximum_lines_per_method' = '80'
    'MA0051.maximum_statements_per_method' = '40'
}

$editor = [Collections.Generic.List[string]]::new()
$editor.Add('# Generated by Scripts/Update-CodeQualityScope.ps1; edit that script, then regenerate.')
$editor.Add('# Fork-added C# only. Upstream files unset style settings and disable these diagnostics.')
$editor.Add('root = true')
$editor.Add('')
$editor.Add('[*.cs]')
foreach ($entry in $style.GetEnumerator()) { $editor.Add("$($entry.Key) = $($entry.Value)") }

$groups = [ordered]@{}
foreach ($path in ($configuration.upstreamFiles | Where-Object { $_ -like '*.cs' })) {
    $directory = [string](Split-Path $path -Parent)
    if (!$groups.Contains($directory)) { $groups[$directory] = [Collections.Generic.List[string]]::new() }
    $groups[$directory].Add((Split-Path $path -Leaf))
}
foreach ($directory in $groups.Keys) {
    $names = @($groups[$directory])
    $pattern = if ($names.Count -eq 1) { $names[0] } else { '{' + ($names -join ',') + '}' }
    if ($directory) { $pattern = $directory.Replace('\', '/') + '/' + $pattern }
    $editor.Add('')
    $editor.Add("[$pattern]")
    foreach ($entry in $style.GetEnumerator()) {
        $value = if ($entry.Key -like 'dotnet_diagnostic.*.severity') { 'none' } else { 'unset' }
        $editor.Add("$($entry.Key) = $value")
    }
}

$ignore = [Collections.Generic.List[string]]::new()
$ignore.Add('# Generated from config/code-quality.json; upstream files are never formatted.')
$ignore.Add('**/bin/')
$ignore.Add('**/obj/')
$ignore.Add('**/*.Designer.cs')
$ignore.Add('**/*.g.cs')
$ignore.Add('**/*.g.i.cs')
# Project XML may be upstream-owned too. This workflow formats source files only.
foreach ($extension in @('csproj', 'proj', 'props', 'targets', 'xml', 'xaml', 'axaml', 'resx')) {
    $ignore.Add("**/*.$extension")
}
foreach ($path in $configuration.upstreamFiles) { $ignore.Add('/' + $path) }

$outputs = @{
    '.editorconfig' = ($editor -join "`r`n") + "`r`n"
    '.csharpierignore' = ($ignore -join "`r`n") + "`r`n"
}
foreach ($name in $outputs.Keys) {
    $path = Join-Path $repository $name
    if ($Check) {
        if (!(Test-Path -LiteralPath $path) -or [IO.File]::ReadAllText($path) -ne $outputs[$name]) {
            throw "$name is out of date. Run Scripts/Update-CodeQualityScope.ps1."
        }
    } else {
        [IO.File]::WriteAllText($path, $outputs[$name], [Text.UTF8Encoding]::new($false))
    }
}
Write-Output ('Upstream exclusions verified: ' + $configuration.upstreamFiles.Count)
