param(
    [switch]$Check
)

# Generates .editorconfig and .csharpierignore. Every source file follows the same rules; only generated
# files and project XML are left to their tools.
$ErrorActionPreference = 'Stop'
$repository = Split-Path $PSScriptRoot -Parent

$style = [ordered]@{
    charset = 'utf-8'
    indent_style = 'space'
    indent_size = '4'
    end_of_line = 'crlf'
    insert_final_newline = 'true'
    trim_trailing_whitespace = 'true'
    max_line_length = '120'
    csharp_new_line_before_open_brace = 'all'
    csharp_new_line_before_else = 'true'
    csharp_new_line_before_catch = 'true'
    csharp_new_line_before_finally = 'true'
    csharp_new_line_before_members_in_object_initializers = 'true'
    csharp_preserve_single_line_statements = 'false'
    csharp_preserve_single_line_blocks = 'false'
    csharp_prefer_braces = 'true:warning'
    'dotnet_diagnostic.IDE0011.severity' = 'warning'
    'dotnet_diagnostic.MA0040.severity' = 'warning'
    'dotnet_diagnostic.MA0042.severity' = 'warning'
    'dotnet_diagnostic.MA0051.severity' = 'warning'
    'dotnet_diagnostic.MA0054.severity' = 'warning'
    'MA0051.maximum_lines_per_method' = '80'
    'MA0051.maximum_statements_per_method' = '40'
}

$editor = [Collections.Generic.List[string]]::new()
$editor.Add('# Generated by Scripts/Update-CodeQualityConfig.ps1; edit that script, then regenerate.')
$editor.Add('# Every C# source follows these rules, including files that came from upstream.')
$editor.Add('root = true')
$editor.Add('')
$editor.Add('[*.cs]')
foreach ($entry in $style.GetEnumerator()) { $editor.Add("$($entry.Key) = $($entry.Value)") }

# WinForms designer output is regenerated by Visual Studio; formatting it would be undone on the next save.
$ignore = [Collections.Generic.List[string]]::new()
$ignore.Add('# Generated by Scripts/Update-CodeQualityConfig.ps1; only generated files and project XML are skipped.')
$ignore.Add('**/bin/')
$ignore.Add('**/obj/')
$ignore.Add('**/*.Designer.cs')
$ignore.Add('**/*.g.cs')
$ignore.Add('**/*.g.i.cs')
foreach ($extension in @('csproj', 'proj', 'props', 'targets', 'xml', 'xaml', 'axaml', 'resx')) {
    $ignore.Add("**/*.$extension")
}

$outputs = @{
    '.editorconfig' = ($editor -join "`r`n") + "`r`n"
    '.csharpierignore' = ($ignore -join "`r`n") + "`r`n"
}
foreach ($name in $outputs.Keys) {
    $path = Join-Path $repository $name
    if ($Check) {
        if (!(Test-Path -LiteralPath $path) -or [IO.File]::ReadAllText($path) -ne $outputs[$name]) {
            throw "$name is out of date. Run Scripts/Update-CodeQualityConfig.ps1."
        }
    } else {
        [IO.File]::WriteAllText($path, $outputs[$name], [Text.UTF8Encoding]::new($false))
    }
}
Write-Output 'Code quality configuration verified: one rule set for all sources.'
